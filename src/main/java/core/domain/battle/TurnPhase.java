package core.domain.battle;

/** 現在進行中のターン位相。 */
public enum TurnPhase {
  /** プレイヤーが入力を受け付け可能。 */
  PLAYER_TURN,
  /** 敵 AI の行動解決中。 */
  ENEMY_TURN,
  /** プレイヤーが死亡してランが終了した状態。 */
  GAME_OVER,
  /** 層内の最終部屋の階段を踏破し、層末ノード選択 (3 択) 待ちの状態 (§15-6 / §15-8)。 */
  CLEARED,
  /** 層内の途中部屋の階段を踏破し、同じ層の次の部屋へ進む待ちの状態 (§15-6 N 層 = N 部屋)。 */
  ROOM_CLEARED,
  /** 最終層のボスを撃破してランに勝利した状態 (§15-6 クリア条件 = 最終層ボス撃破)。 */
  RUN_CLEARED
}
