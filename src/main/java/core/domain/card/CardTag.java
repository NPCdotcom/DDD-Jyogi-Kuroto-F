package core.domain.card;

/**
 * カードの大分類タグ (§15-3)。
 *
 * <p>1 枚のカードは 1 つのタグを持つ。タグは UI でのアイコン表示や、将来のシナジー判定 (例:「ATTACK カードを 3 枚使用時に追加効果」) に用いる。
 */
public enum CardTag {
  /** 攻撃 (敵にダメージを与える)。 */
  ATTACK,
  /** 移動 (自身の座標を変える)。 */
  MOVEMENT,
  /** 強化 (一時的なステ上昇)。 */
  BUFF,
  /** 罠 (タイルに効果を残す)。 */
  TRAP
}
